"""AI workspaces of Agent Management, from seed/aim/workspaces/*.yaml: governed access to models for teams, with a budget
for each person.

A workspace is an API product plus the LLM proxy that carries its models. A file describes:

    budgets      one plan of the product each: a cost limit per member, optionally a request rate
    components   the models of the LLM proxy, from a provider of the catalog
    router       the steps every budget runs before the call (spend-aware routing...); the ones a control of
                 seed/controls.yaml names (controls.py) are enabled or disabled as the mode says, on every run
    analytics    what the gateway records for each call
    members      platform users, each with an application, a subscription to a budget and an API key

Everything is found by name and written only when it differs, so a second run writes nothing. What waits for a
deployment (budgets, router, reporter settings) is deployed once, at the end, and the seed then waits for the gateway.
Then the members that seed/refills.yaml names (refills.py) get their budget back, whatever they spent since the last run.
The keys are generated by Gravitee: whoever needs one reads it through the Gamma API, the seed writes none down.
"""

import json
import os
import time
from urllib.parse import quote

from . import controls
from . import gamma
from . import refills
from .common import Api, SeedError, excerpt, files, has_seed, load, log, owned, pause, record, recorded, setting, wait_until, waits_for_gateway

SECTION = "aim-workspaces"
DEPENDS = ("aim_catalog",)   # the modules whose work this one reads on the platform (schedule.py)
# The folder of the seed it owns
FOLDERS = ("aim/workspaces",)
# The Gamma modules it fills: seed.py checks that the platform serves them before it changes anything
GAMMA = ("aim",)
# What it records, dependents first
ORDER = ["workspace", "workspace-user"]


def subset(wanted, current):
    """Whether everything in `wanted` is in `current`: the platform adds defaults, which are not a change."""
    if isinstance(wanted, dict):
        return isinstance(current, dict) and all(k in current and subset(v, current[k]) for k, v in wanted.items())
    if isinstance(wanted, list):
        return isinstance(current, list) and len(wanted) == len(current) and all(subset(w, c) for w, c in zip(wanted, current))
    return wanted == current


def budget_body(spec):
    """Budgets are kept in millionths of a dollar: 5 dollars are 5,000,000."""
    return {"costBudget": round(float(spec["dollars"]) * 1_000_000), "period": spec["period"],
            "requestRate": spec.get("requestRate")}


def step(spec):
    """A step of the router. The API wants its configuration as a JSON string."""
    return {"policy": spec["policy"], "name": spec.get("name", spec["policy"]), "enabled": spec.get("enabled", True),
            "configuration": json.dumps(spec.get("configuration", {})), "condition": spec.get("condition")}


def parsed(steps):
    """Steps with their configuration read, so that the platform's own formatting of it is not a difference."""
    return [{**s, "configuration": json.loads(s.get("configuration") or "{}"), "condition": s.get("condition") or None}
            for s in steps]


def aliases(models):
    return {m["name"]: sorted(m.get("aliases") or []) for m in models}


class AiWorkspaces:
    def __init__(self):
        self.g = gamma.Gamma()
        self.aim = self.g.aim
        self.changed_at = None   # when the seed last wrote something the gateway has to pick up

    def connect(self):
        self.g.connect(SECTION, lambda: self.aim.get("/ai-workspaces", params={"perPage": 1}), "AI workspaces")

    def touched(self):
        self.changed_at = time.time()

    # --- A workspace from its file ------------------------------------------------------------

    def apply(self, spec):
        refilled = refills.of(spec["name"], [member["sourceId"] for member in spec["members"]])
        workspace = self.workspace(spec)
        base = f"/ai-workspaces/{workspace['id']}"
        budgets = self.budgets(base, spec["budgets"])
        self.components(base, spec["components"])
        if "router" in spec:
            self.router(base, spec["router"], controls.of("workspace", spec["name"]))
        if "analytics" in spec:
            self.analytics(base, spec["analytics"])
        members = self.members(base, spec["members"], budgets)
        self.deploy(base)
        self.wait_live(base, spec["name"], members)
        refills.run(refilled, {source: member["subscriptionId"] for source, member, _ in members})
        log(SECTION, f"✓ AI workspace {spec['name']}")

    def workspace(self, spec):
        """Creates the workspace with its first budget, or updates its details. Its gateway path comes from its name
        when it is created and never changes."""
        name, version, description = spec["name"], str(spec.get("version", "1.0")), spec.get("description")
        found = next((w for w in self.aim.rows("/ai-workspaces", gamma.WORKSPACES, q=name) if w["name"] == name), None)
        if found and not recorded(SECTION, "workspace", found["id"]):
            raise SeedError(f"AI workspace {name} exists and the seed did not create it")
        if found is None:
            body = {"name": name, "version": version, "defaultBudget": budget_body(spec["budgets"][0])}
            if description:
                body["description"] = description
            found = self.aim.post("/ai-workspaces", json=body).json()
            record(SECTION, "workspace", "AI workspaces", name, found["id"])
            self.touched()
            log(SECTION, f"✓ AI workspace created: {name}")
        elif (found.get("version"), found.get("description")) != (version, description):
            body = {"name": name, "version": version, "tags": found.get("tags", [])}
            if description:
                body["description"] = description
            self.aim.put(f"/ai-workspaces/{found['id']}", json=body)
            self.touched()
            log(SECTION, f"✓ AI workspace updated: {name}")
        return found

    # --- Budgets ------------------------------------------------------------------------------

    def budgets(self, base, specs):
        """{name: budget} once each budget of the file exists as written. Names are not unique for the API: they are
        looked up here. The workspace starts with one budget, named Default, which becomes the first of the file."""
        live = self.aim.rows(f"{base}/budgets", gamma.LISTS)
        starting = next((b for b in live if b["name"] == "Default"), None)
        out = {}
        for spec in specs:
            body = {"name": spec["name"], **budget_body(spec)}
            found = next((b for b in live if b["name"] == spec["name"]), None)
            if found is None and spec is specs[0]:
                found = starting
            if found is None:
                found = self.aim.post(f"{base}/budgets", json=body).json()
                self.touched()
                log(SECTION, f"  ✓ Budget created: {spec['name']}")
            elif any(found.get(key) != value for key, value in body.items()):
                self.aim.put(f"{base}/budgets/{found['id']}", json=body)
                self.touched()
                log(SECTION, f"  ✓ Budget updated: {spec['name']}")
            out[spec["name"]] = {"id": found["id"], "costBudget": body["costBudget"]}
        return out

    # --- Models -------------------------------------------------------------------------------

    def provider_id(self, slug):
        found = next((p for p in self.aim.rows("/providers", gamma.CATALOG) if p["slug"] == slug), None)
        if found is None:
            raise SeedError(f"AI provider {slug} is not in the catalog: seed/aim/providers creates it before the workspace")
        return found["id"]

    def components(self, base, specs):
        """The models of each provider, as the file lists them. The platform takes the set of models of a provider one
        model at a time (add, remove) and its aliases and governance as one edit that leaves the set as it is."""
        live = self.aim.get(f"{base}/models").json()
        for spec in specs:
            wanted = {"kind": "managed", "providerId": self.provider_id(spec["provider"]),
                      "models": [{"name": m["name"], "aliases": m.get("aliases", [])} for m in spec["models"]],
                      "modelGovernance": {"aliasOnly": False, "modelPattern": "",
                                          "prefixPolicy": {"policy": spec.get("prefixPolicy", "PREFIXED_BOTH")}}}
            found = next((c for c in live if c["kind"] == "managed" and c["providerId"] == wanted["providerId"]), None)
            if found is None:
                self.aim.post(f"{base}/models/_bulk", json=[wanted])
                changed = True
            else:
                changed = self.models_of(base, wanted, found)
            if changed:
                self.touched()
                log(SECTION, f"  ✓ Models of {spec['provider']}: {', '.join(m['name'] for m in spec['models'])}")

    def models_of(self, base, wanted, found):
        """Adds the models the provider lacks (the others and their aliases stay), removes those the file does not
        list, then sets aliases and governance when they differ."""
        have, want = aliases(found["models"]), aliases(wanted["models"])
        key = quote(wanted["providerId"], safe="")
        added = [m for m in wanted["models"] if m["name"] not in have]
        if added:
            self.aim.post(f"{base}/models/_bulk", json=[{**wanted, "models": added}])
        for name in sorted(have.keys() - want.keys()):
            self.aim.delete(f"{base}/models/{key}/{quote(name, safe='')}")
        settings = (any(have[name] != want[name] for name in have.keys() & want.keys())
                    or not subset(wanted["modelGovernance"], found.get("modelGovernance") or {}))
        if settings:
            self.aim.put(f"{base}/models/{key}", json=wanted)
        return bool(added or have.keys() - want.keys() or settings)

    # --- Router and reporter settings ---------------------------------------------------------

    def router(self, base, spec, found=()):
        """The steps are checked against their policy's schema when saved: a wrong one is a 400 with its JSON path. The
        steps a control names are written enabled or not, as the mode says, in both modes: one someone switched is put back."""
        wanted = {"request": [step(s) for s in spec.get("request", [])], "response": [step(s) for s in spec.get("response", [])]}
        controls.align_router(wanted, found)
        current = self.aim.get(f"{base}/router").json()
        if not all(subset(parsed(wanted[side]), parsed(current.get(side, []))) for side in wanted):
            self.aim.put(f"{base}/router", json=wanted)
            self.touched()
            log(SECTION, f"  ✓ Router: {len(wanted['request'])} request steps, {len(wanted['response'])} response steps")
        if found:
            log(SECTION, f"  Router controls are {'on' if controls.protected() else 'off'}: {controls.named(found)}")

    def analytics(self, base, wanted):
        if not subset(wanted, self.aim.get(f"{base}/analytics").json()["analytics"]):
            self.aim.put(f"{base}/analytics", json={"analytics": wanted})
            self.touched()
            log(SECTION, "  ✓ Reporter settings")

    # --- Members ------------------------------------------------------------------------------

    def user(self, spec):
        """The id of a platform user, created in the Gravitee directory (no password: nobody signs in as them, but they
        own an application and a key like anyone) unless it belongs to another source, which is only found."""
        source, source_id = spec.get("source", "gravitee"), spec["sourceId"]
        users = self.g.org_v1.get("/users", params={"q": source_id, "size": 100}).json().get("data", [])
        found = next((u for u in users if u.get("source") == source and u.get("sourceId") == source_id), None)
        if found:
            return found["id"]
        if source != "gravitee":
            if spec.get("optional"):
                log(SECTION, f"! {source_id} is not a user of the platform yet: left out")
                return None
            raise SeedError(f"User {source_id} ({source}) is not known to the platform: it signs in once first")
        made = self.g.org_v1.post("/users", json={"source": source, "sourceId": source_id, "firstname": spec["firstname"],
                                                  "lastname": spec["lastname"], "email": spec["email"], "service": False}).json()
        record(SECTION, "workspace-user", "workspace users", source_id, made["id"])
        log(SECTION, f"  ✓ User created: {source_id}")
        return made["id"]

    def members(self, base, specs, budgets):
        """[(source id, membership, budget)]: each user in the budget the file names, moved there if elsewhere (the key
        stays the same when moved)."""
        live = self.aim.rows(f"{base}/users", gamma.LISTS)
        out = []
        for spec in specs:
            if spec["budget"] not in budgets:
                raise SeedError(f"User {spec['sourceId']}: budget {spec['budget']} is not in the file")
            user_id = self.user(spec)
            if user_id is None:
                continue
            budget = budgets[spec["budget"]]
            found = next((m for m in live if m["userId"] == user_id), None)
            if found is None or found["budgetId"] != budget["id"]:
                if found is None:
                    found = self.aim.post(f"{base}/users", json={"userId": user_id, "budgetId": budget["id"]}).json()
                else:
                    found = self.aim.put(f"{base}/users/{found['subscriptionId']}", json={"budgetId": budget["id"]}).json()
                self.touched()
                log(SECTION, f"  ✓ {spec['sourceId']} is in {spec['budget']}")
            out.append((spec["sourceId"], found, budget))
        return out

    # --- Deployment ---------------------------------------------------------------------------

    def deploy(self, base):
        """Budgets, router and reporter settings reach the gateway with a deployment; models and members do not need
        one. It is asked for only when the platform says something waits."""
        waiting = (self.aim.get(base).json()["deploymentState"] != "DEPLOYED"
                   or self.aim.get(f"{base}/analytics").json().get("needsDeploy"))
        if waiting:
            self.aim.post(f"{base}/_deploy", json={})
            self.touched()
            log(SECTION, "  ✓ Deployed")

    def wait_live(self, base, name, members):
        """Waits until the gateway accepts a member's key with the member's budget (the proxy and the plans reach it in
        different rounds, so a first answer can come from the previous deployment), then until two synchronizations
        have passed since the last change. Skipped when the seed does not know the gateway."""
        gateway = os.getenv("GATEWAY_INTERNAL_URL")
        if not gateway or not members or not waits_for_gateway():
            return
        _, member, budget = members[0]
        key = self.aim.get(f"{base}/users/{member['subscriptionId']}/api-key").json()["apiKey"]
        path = self.aim.get(base).json()["contextPath"]
        entry = Api(gateway)

        def accepted():
            answer = entry.send("GET", f"{path}/models", headers={"Authorization": f"Bearer {key}"}, timeout=10)
            if answer.status_code not in (200, 429) or answer.headers.get("X-Cost-Rate-Limit-Limit") != str(budget["costBudget"]):
                raise SeedError(f"HTTP {answer.status_code} {excerpt(answer.text, 200)}")

        wait_until(SECTION, f"{name} on the gateway ({path})", accepted, int(setting("GATEWAY_READY_TIMEOUT", "300")))
        if self.changed_at:
            settled = self.changed_at + 2 * float(setting("GATEWAY_SYNC_SECONDS", "5")) + 1
            pause(max(0.0, settled - time.time()))

    # --- Removal ------------------------------------------------------------------------------

    def delete_workspace(self, workspace_id, users):
        """Deletes the workspace with its LLM proxy, budgets and subscriptions, and returns the applications of the
        given users that it leaves behind: an application is shared by every workspace of its user."""
        base = f"/ai-workspaces/{workspace_id}"
        if self.aim.get(base, expect=(200, 404)).status_code == 404:
            return []
        applications = [m["applicationId"] for m in self.aim.rows(f"{base}/users", gamma.LISTS) if m["userId"] in users]
        self.aim.delete(base)
        return applications

    def delete_application(self, application_id):
        """Only when no subscription uses it any more."""
        subscriptions = self.g.v1.get(f"/applications/{application_id}/subscriptions", params={"size": 1}).json()
        if not subscriptions.get("data"):
            self.g.v1.delete(f"/applications/{application_id}")


def seed():
    if not has_seed(*FOLDERS):
        return   # before any setting is read or any connection made: a playground that does not seed this is untouched
    workspaces = AiWorkspaces()
    workspaces.connect()
    for path in files("aim", "workspaces"):
        workspaces.apply(load(path))


def remove(records):
    """The workspace, then the applications of the users the seed created if nothing else uses them, then those users.
    The platform keeps a deleted user archived: the same name can be created again."""
    mine = owned(records, SECTION, ORDER)
    if not mine:
        return
    workspaces = AiWorkspaces()
    workspaces.connect()
    users = [x for x in mine if x["kind"] == "workspace-user"]
    applications = []
    for x in (x for x in mine if x["kind"] == "workspace"):
        applications += workspaces.delete_workspace(x["id"], {u["id"] for u in users})
        log(SECTION, f"✓ Deleted AI workspace '{x['name']}'")
    for application in applications:
        workspaces.delete_application(application)
    for x in users:
        workspaces.g.org_v1.delete(f"/users/{x['id']}")
        log(SECTION, f"✓ Deleted workspace user '{x['name']}'")
